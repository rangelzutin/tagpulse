export class HustlerSchemaValidationError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "HustlerSchemaValidationError";
  }
}

export function validateHustlerTableColumns(
  table: HustlerSupportedTable,
  actualColumns: string[],
): void {
  const expected = HUSTLER_TABLE_COLUMNS[table];
  if (!expected) {
    throw new HustlerSchemaValidationError(
      `Unsupported table '${table}' in Hustler schema validation`,
    );
  }

  if (actualColumns.length !== expected.length) {
    throw new HustlerSchemaValidationError(
      `Table '${table}' column count mismatch: expected ${expected.length}, got ${actualColumns.length}`,
    );
  }

  for (let i = 0; i < expected.length; i++) {
    if (actualColumns[i] !== expected[i]) {
      throw new HustlerSchemaValidationError(
        `Table '${table}' column mismatch at index ${i}: expected '${expected[i]}', got '${actualColumns[i]}'`,
      );
    }
  }
}
